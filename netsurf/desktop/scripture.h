#ifndef NETSURF_DESKTOP_SCRIPTURE_H
#define NETSURF_DESKTOP_SCRIPTURE_H

#include <stdbool.h>
#include <stddef.h>

/** A parsed, validated reference. vstart == 0 means "whole chapter". */
typedef struct scripture_ref {
	int book;	/**< 1 (Genesis) .. 66 (Revelation) */
	int chapter;	/**< 1-based */
	int vstart;	/**< first verse, or 0 for the whole chapter */
	int vend;	/**< last verse (== vstart for a single verse) */
} scripture_ref;

/* generated by tools/gen_kjv.py into scripture_kjv.c */
extern const size_t scripture_kjv_raw_len;
extern const size_t scripture_kjv_z_len;
extern const unsigned char scripture_kjv_z[];

/**
 * Parse text that is ENTIRELY a reference, e.g. "John 3:16", "1 Cor 13:4-7",
 * "Ps 23", "Jude 3", "Song of Solomon 2:1".  Book names and common
 * abbreviations are case-insensitive; chapter and verse are validated
 * against the KJV so that "ti 84" or "John 99:1" are rejected.
 *
 * \param text	text (need not be NUL terminated)
 * \param len	length of text
 * \param ref	filled on success
 */
bool scripture_parse(const char *text, size_t len, scripture_ref *ref);

/** Find the first "Book chapter:verse[-verse]" reference anywhere in text. */
bool scripture_find(const char *text, size_t len, scripture_ref *ref);

/** Canonical English book name (NULL if book is out of range). */
const char *scripture_book_name(int book);

/** Write "John 3:16-18" style label into buf. */
void scripture_label(const scripture_ref *ref, char *buf, size_t buflen);

/** malloc'd Bible Gateway NKJV passage URL, or NULL on out of memory. */
char *scripture_url(const scripture_ref *ref);

/**
 * Copy the verse text (KJV) into buf, truncating with "..." when it does
 * not fit.  \return bytes written (0 if the text is unavailable).
 */
size_t scripture_text(const scripture_ref *ref, char *buf, size_t buflen);

/**
 * Build a one-line preview for a hovered link.  link_text is tried first
 * (it must be a whole reference); otherwise a reference with chapter AND
 * verse is searched for in the percent-decoded url.
 */
bool scripture_preview(const char *link_text, const char *url,
		char *out, size_t outlen);

/** Release the inflated KJV text. */
void scripture_finalise(void);

#endif
