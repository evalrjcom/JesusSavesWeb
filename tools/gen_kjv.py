#!/usr/bin/env python3
"""JesusSaves v1.1.2 - generate netsurf/desktop/scripture_kjv.c from the KJV verse JSON.

Source text: npm package "kjv" (verses-1769.json, public-domain 1769 King James text,
packaging released into the public domain).  Usage:
    python3 tools/gen_kjv.py /path/to/verses-1769.json netsurf/desktop/scripture_kjv.c
Record format (one per line, canonical order): "<book 1-66>:<chapter>:<verse>\t<text>\n"
The blob is zlib-compressed; scripture.c inflates it on first use.
"""
import json, re, sys, zlib

BOOKS = ["Genesis","Exodus","Leviticus","Numbers","Deuteronomy","Joshua","Judges","Ruth",
"1 Samuel","2 Samuel","1 Kings","2 Kings","1 Chronicles","2 Chronicles","Ezra","Nehemiah",
"Esther","Job","Psalms","Proverbs","Ecclesiastes","Song of Solomon","Isaiah","Jeremiah",
"Lamentations","Ezekiel","Daniel","Hosea","Joel","Amos","Obadiah","Jonah","Micah","Nahum",
"Habakkuk","Zephaniah","Haggai","Zechariah","Malachi","Matthew","Mark","Luke","John","Acts",
"Romans","1 Corinthians","2 Corinthians","Galatians","Ephesians","Philippians","Colossians",
"1 Thessalonians","2 Thessalonians","1 Timothy","2 Timothy","Titus","Philemon","Hebrews",
"James","1 Peter","2 Peter","1 John","2 John","3 John","Jude","Revelation"]
idx = {n: i + 1 for i, n in enumerate(BOOKS)}
idx["Solomon's Song"] = 22   # the JSON names this book "Solomon's Song"

def main(src, dst):
    verses = json.load(open(src, encoding="utf-8"))
    rows = []
    for ref, text in verses.items():
        m = re.match(r"^(.+) (\d+):(\d+)$", ref)
        b = idx[m.group(1)]
        text = text.lstrip("# ").replace("[", "").replace("]", "")   # drop paragraph mark / italics brackets
        text = " ".join(text.split())
        text = (text.replace("’", "'").replace("‘", "'")
                    .replace("“", '"').replace("”", '"')
                    .replace("—", " - ").replace("–", "-"))
        text.encode("ascii")                                          # fail loudly on anything non-ASCII
        rows.append((b, int(m.group(2)), int(m.group(3)), text))
    rows.sort()
    assert len(rows) == 31102, len(rows)
    raw = "".join("%d:%d:%d\t%s\n" % r for r in rows).encode("ascii")
    z = zlib.compress(raw, 9)
    with open(dst, "w") as f:
        f.write("/* GENERATED by tools/gen_kjv.py - do not edit.  KJV (1769), public domain. */\n")
        f.write("#include <stddef.h>\n#include \"desktop/scripture.h\"\n")
        f.write("const size_t scripture_kjv_raw_len = %d;\nconst size_t scripture_kjv_z_len = %d;\n" % (len(raw), len(z)))
        f.write("const unsigned char scripture_kjv_z[%d] = {\n" % len(z))
        for i in range(0, len(z), 24):
            f.write(",".join(str(c) for c in z[i:i+24]) + ",\n")
        f.write("};\n")
    print("verses", len(rows), "raw", len(raw), "zlib", len(z))

main(sys.argv[1], sys.argv[2])
